/* 平台名（中文）→ 知识条目。兼容 PLATFORM_MAP 的同名写法。 */
function pfKnow(name){
  if(!name) return null;
  for(var i=0;i<PLATFORMS.length;i++){
    var p = PLATFORMS[i];
    if(p.n === name || p.k === name) return p;
  }
  /* 兜底：视频号/朋友圈归属微信生态 */
  if(name === '视频号' || name === '朋友圈') return pfKnow('公众号 / 视频号');
  return null;
}

/* 平台 key（xhs/dy/...）→ 知识条目 */
function pfKnowByKey(k){
  if(!k) return null;
  for(var i=0;i<PLATFORMS.length;i++){ if(PLATFORMS[i].k === k) return PLATFORMS[i]; }
  return null;
}

/* ------------------------------------------------------------
 * 按平台过滤违禁词：WORD_RULES 的 pf 字段标明该词适用哪些平台。
 *
 * 注意：不能只取 red/yellow。实际核查发现——平台专属词（有 pf 的）
 * 全部是 blue 级（平台规则，如小红书「私信我」「加微信」、抖音
 * 「点小黄车」「手慢无」），而 red/yellow 是法律层、全平台通用。
 * 只取 red/yellow 会一条平台专属词都拿不到，平台适配就失去意义。
 *
 * 因此排序为：平台专属优先 → 其次红线 → 风险 → 平台规则。
 * 级别含义在提示词里注明（red=违法，blue=不违法但会被限流/处置）。
 * ------------------------------------------------------------ */
function pfWordRisks(pfKey, maxN){
  var max = maxN || 12;
  var LV_ORDER = { red:0, yellow:1, blue:2 };
  if(!pfKey || typeof WORD_RULES === 'undefined') return [];
  var hit = [];
  for(var i=0;i<WORD_RULES.length;i++){
    var r = WORD_RULES[i];
    /* 无 pf = 全平台通用；有 pf = 仅列指定平台 */
    if(!r.pf || r.pf.length === 0) hit.push({r:r, spec:false});
    else if(r.pf.indexOf(pfKey) > -1) hit.push({r:r, spec:true});
  }
  hit.sort(function(a,b){
    if(a.spec !== b.spec) return a.spec ? -1 : 1;   /* 平台专属最前 */
    return (LV_ORDER[a.r.lv] || 9) - (LV_ORDER[b.r.lv] || 9);
  });
  return hit.slice(0, max);
}

/* 级别 → 提示词里的说法 */
function pfLvText(lv){
  if(lv === 'red') return '红线（违法）';
  if(lv === 'yellow') return '风险';
  return '平台规则（不违法但会被限流/处置）';
}

/* ------------------------------------------------------------
 * 品牌调性 → 语气指令
 * 把 BC_DIMS 的打分（1-5）转成人能执行的语气要求。
 * 只取与品类基准偏离较大的维度：和基准一致的维度不需要强调。
 * ------------------------------------------------------------ */
function pfToneGuide(dims, base){
  if(!dims) return [];
  var out = [];
  var HIGH = { func:'讲清楚它到底解决什么问题，用具体参数和场景，少用形容词',
    price:'可以谈价值但要克制，不要出现打折促销话术',
    channel:'强调易得性与便利，降低行动门槛',
    speed:'强调快、省事、即时见效，用时间短句',
    sensory:'多写感官细节：质地、气味、触感、声音',
    service:'语气要有温度，主动替读者想到后续问题',
    emotion:'先共情再讲产品，允许情绪化表达',
    belonging:'用圈内语言，制造"我们这一类人"的归属感',
    status:'语气克制有分寸，不讨好、不叫卖，留白与暗示',
    values:'把产品放进更大的价值主张里讲，允许有态度' };
  var LOW = { func:'不必堆参数，重点讲体验与感受',
    price:'不要强调价格，避免让人先想到便宜',
    channel:'不要强调随处可买，稀缺性更重要',
    speed:'不要强调快，慢与过程本身是价值',
    sensory:'不要堆砌感官形容词',
    service:'保持距离感，不要过度热情',
    emotion:'保持理性克制，不要煽情',
    belonging:'不要强行拉圈子',
    status:'不要端着，语气要平易',
    values:'不要上价值，就事论事' };
  if(typeof BC_DIMS === 'undefined') return out;
  BC_DIMS.forEach(function(d){
    var v = dims[d.k];
    if(v == null) return;
    var b = (base && base[d.k] != null) ? base[d.k] : 3.0;
    var diff = v - b;
    if(diff >= 0.8 && HIGH[d.k]) out.push({ k:d.k, n:d.n, dir:'高', t:HIGH[d.k] });
    else if(diff <= -0.8 && LOW[d.k]) out.push({ k:d.k, n:d.n, dir:'低', t:LOW[d.k] });
  });
  return out;
}

/* ------------------------------------------------------------
 * 界面：平台知识预览 + 注入开关
 * 让用户看见「即将注入什么」，而不是黑箱。
 * ------------------------------------------------------------ */
function pfRenderKnow(){
  var box = document.getElementById('c_pfknow');
  if(!box) return;
  var pfEl = document.getElementById('c_platform');
  var lenEl = document.getElementById('c_len');
  var name = pfEl ? pfEl.value : '';
  var len = lenEl ? lenEl.value : '';
  var p = pfKnow(name);
  if(!p){ box.innerHTML = ''; return; }
  var pfKey = (typeof PLATFORM_MAP !== 'undefined') ? PLATFORM_MAP[name] : '';
  var risks = pfWordRisks(pfKey, 12);

  var h = '';
  h += '<div class="pfknow__hd">' + (p.em || '') + ' ' + p.n + '　<span class="pfknow__tag">' + (len || '') + '</span></div>';
  if(p.lenBand && p.lenBand[len]){
    h += '<div class="pfknow__line"><b>篇幅</b>' + p.lenBand[len] + '</div>';
  }
  h += '<div class="pfknow__line"><b>调性</b>' + p.tone + '</div>';
  h += '<div class="pfknow__line"><b>结构</b>' + p.structure.join(' → ') + '</div>';
  h += '<div class="pfknow__line"><b>禁忌</b>' + p.taboo.length + ' 条：' + p.taboo[0] + ' 等</div>';
  if(risks.length){
    var words = risks.slice(0, 6).map(function(x){ return x.r.t; }).join('、');
    h += '<div class="pfknow__line"><b>违禁词</b>将注入 ' + risks.length + ' 条高危词：' + words + '…</div>';
  }
  box.innerHTML = h;
}

/* 绑定：平台 / 字数 / 开关变化时刷新预览 */
function pfBindKnow(){
  var pfEl = document.getElementById('c_platform');
  var lenEl = document.getElementById('c_len');
  var injEl = document.getElementById('c_inject');
  if(pfEl) pfEl.addEventListener('change', pfRenderKnow);
  if(lenEl) lenEl.addEventListener('change', pfRenderKnow);
  if(injEl) injEl.addEventListener('change', pfRenderKnow);
  pfRenderKnow();
}
